/**
 * 使用文档的正文数据。
 *
 * 为什么把文档写成结构化数据而不是一段 Markdown 字符串：
 * 手册要同时供两个地方消费 —— 应用内的「使用文档」面板（需要按章节分栏、
 * 按关键字过滤、命中计数）以及仓库里的 docs\使用文档.md（需要标准 Markdown）。
 * 若以 Markdown 为源，界面侧就得在渲染时解析一遍；而应用内检索又要求
 * 「哪一章命中了几处」这种结构信息，正则切段落很快会失真。
 * 反过来由结构化数据生成 Markdown 是纯粹的拼字符串，不会出错。
 *
 * 因此这里是唯一的正文来源：面板直接渲染，docs 里的 .md 由
 * scripts/gen-user-guide.mjs 从本文件生成（npm run docs:guide）。
 */

export type GuideBlock =
  | { t: 'p'; text: string }
  | { t: 'bullets'; items: string[] }
  /** 有序步骤。与 bullets 分开是因为「第几步」本身是信息 */
  | { t: 'steps'; items: string[] }
  | { t: 'table'; head: string[]; rows: string[][] }
  | { t: 'code'; text: string }
  /** 提示条：容易踩的坑、与直觉相反的行为 */
  | { t: 'note'; text: string }
  /** 小标题：一章内部的分节 */
  | { t: 'h'; text: string }

export interface GuideSection {
  id: string
  title: string
  /** 目录里的一句话说明，也参与检索 */
  summary: string
  /** 补充检索词：英文名、协议缩写、用户可能搜的同义说法 */
  keywords: string
  blocks: GuideBlock[]
}

/** 供搜索用：把一个区块摊平成纯文本 */
export function blockText(b: GuideBlock): string {
  switch (b.t) {
    case 'p':
    case 'note':
    case 'code':
    case 'h':
      return b.text
    case 'bullets':
    case 'steps':
      return b.items.join(' ')
    case 'table':
      return [b.head.join(' '), ...b.rows.map((r) => r.join(' '))].join(' ')
  }
}

/** 整章纯文本，检索命中计数用 */
export function sectionText(s: GuideSection): string {
  return [s.title, s.summary, s.keywords, ...s.blocks.map(blockText)].join('\n')
}

